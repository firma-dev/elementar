export function dayLabel(date: string): string {
  const [, month, day] = date.split('-')
  const index = Number(month) - 1
  return `${Number(day)} ${MONTH_GENITIVE[index] ?? ''}`.trim()
}

const WEEKDAY = ['вс', 'пн', 'вт', 'ср', 'чт', 'пт', 'сб'] as const

/**
 * День недели, сокращённо.
 *
 * Нужен там, где человек вспоминает не сумму, а обстоятельства: перевод в
 * пятницу вечером и перевод в понедельник утром — почти наверняка разные вещи,
 * хотя в выписке отличаются только числом.
 *
 * Считается из строки, а не через `new Date(date)`: разбор ISO-даты браузером
 * даёт полночь UTC, и в отрицательных поясах день уезжал бы на предыдущий.
 */
export function weekdayLabel(date: string): string {
  const [year, month, day] = date.split('-').map(Number)
  if (year === undefined || month === undefined || day === undefined) return ''
  const utc = Date.UTC(year, month - 1, day)
  return WEEKDAY[new Date(utc).getUTCDay()] ?? ''
}

/**
 * FNV-1a, 32 бита. Криптографии здесь не нужно: идентификатор нужен только чтобы
 * ручная правка нашла свою строку после перезагрузки выписки.
 */
function fnv1a(input: string): string {
  let hash = 0x811c9dc5
  for (let i = 0; i < input.length; i += 1) {
    hash ^= input.charCodeAt(i)
    hash = Math.imul(hash, 0x01000193) >>> 0
  }
  return hash.toString(16).padStart(8, '0')
}

/**
 * Идентификатор операции: счёт и содержимое строки, больше ничего.
 *
 * Счёт в ключе обязателен — без него две одинаковые покупки кофе с дебетовой и
 * с кредитной карты получают один идентификатор, и вторая молча исчезает при
 * склейке, то есть пропадают деньги.
 *
 * А вот выписки в ключе быть не должно, хотя раньше она там была. Ключ выписки
 * считался из «первая дата | последняя дата | число строк», и повторная
 * выгрузка того же счёта неделю спустя давала другой ключ: все ранее
 * загруженные операции приезжали как новые, картина задваивалась, а ручные
 * правки теряли свои строки. Ежедневный сценарий целиком стоит на повторном
 * импорте, поэтому ключ теперь зависит только от того, что не меняется от
 * выгрузки к выгрузке (Д-026).
 *
 * Одинаковые операции в один день (две поездки по 300 ₽) различаются порядковым
 * номером дубля.
 */
export function txId(
  date: string,
  amount: Kopeck,
  description: string,
  duplicate: number,
  account = '',
): string {
  const body = fnv1a(`${account}|${date}|${amount}|${description}`)
  const tail = duplicate === 0 ? '' : `-${duplicate}`
  return `${body}${tail}`
}

/**
 * Ключ счёта из того, чем банк его назвал: номер карты, номер счёта или, если
 * ни того ни другого в файле нет, имя файла. Имя файла банки выгружают
 * одинаково от раза к разу, поэтому как запасной ключ оно годится; ошиблись —
 * счёт переименовывается в переключателе.
 */
export function accountKey(raw: string): string {
  const clean = raw.trim()
  if (clean === '') return 'default'
  // Ключ — по последним четырём цифрам, а не по написанию.
  //
  // Один и тот же банк пишет карту то «**3523», то «*3523», то «553691******3523».
  // По написанию это три разных счёта: в переключателе появлялись две
  // одинаковые с виду плашки «Райффайзен Банк ·3523», и операции делились
  // между ними пополам. Последние четыре цифры — то единственное, что банк не
  // меняет от выгрузки к выгрузке.
  const digits = clean.replace(/\D+/g, '')
  const tail = digits.length >= 4 ? digits.slice(-4) : ''
  return fnv1a(tail === '' ? clean.toUpperCase() : `КАРТА ${tail}`)
}

/**
 * Имя выписки из имени файла: без расширения и без следов повторного
 * скачивания.
 *
 * Когда банк не выгрузил номер карты, различать счета нечем, кроме имени
 * файла, — и оно от выгрузки к выгрузке не меняется (Д-026). Но меняет его
 * браузер: второй скачанный файл Chrome сохраняет как «выписка (1).csv»,
 * Safari — как «выписка-1.csv», проводник — «выписка — копия.csv».
 *
 * Без нормализации это второй счёт: удваивались траты, доход, остаток и все
 * графики, а дедупликация не срабатывала, потому что идентификатор операции
 * считается в том числе от счёта. Человек видел ровно вдвое больший год и
 * никакого предупреждения.
 */
export function statementName(filename: string): string {
  return (
    filename
      .replace(/\.[a-z0-9]{1,5}$/i, '')
      // « (1)», «(12)» в конце — Chrome, Firefox, Edge.
      .replace(/\s*\(\d+\)\s*$/, '')
      // «-1», «-2» в конце — Safari. Только один-два разряда: «выписка-2024»
      // это год, а не повтор.
      .replace(/-\d{1,2}$/, '')
      // «копия», «copy» с любым обрамлением.
      .replace(/\s*[—–-]?\s*(копия|copy)\s*\d*$/i, '')
      .trim() || filename
  )
}
