/**
 * Куда сворачивается дополнительная категория, пока она выключена.
 *
 * Родитель выбран так, чтобы свёртка не врала: такси — это транспорт, а не
 * «прочее», и человек, не включивший такси, всё равно видит эти деньги там,
 * где ожидает. Там, где честного родителя нет (образование), стоит «Прочее» —
 * это и значит «сказать про них больше нечего».
 */
export const PARENT: Readonly<Partial<Record<Category, Category>>> = {
  // Продукты и кафе — это еда. Разделение нужно не всем и не всегда: в
  // картине месяца «Еда 84 189» отвечает на вопрос, а «Продукты 55 005» и
  // «Кафе 29 184» по отдельности заставляют складывать в уме. Кому разделение
  // нужно — включает его в «Ещё категориях», и там же видно, сколько за ним
  // стоит.
  Продукты: 'Еда',
  'Кафе и рестораны': 'Еда',
  Такси: 'Транспорт',
  Автомобиль: 'Транспорт',
  Путешествия: 'Транспорт',
  Маркетплейсы: 'Покупки',
  Одежда: 'Покупки',
  'Дом и техника': 'Покупки',
  Дети: 'Покупки',
  Питомцы: 'Покупки',
  Красота: 'Здоровье',
  // Не «Продукты»: те сами стали дополнительной, а родителем дополнительной
  // может быть только основная — иначе свёртка уводит в категорию, которой на
  // экране тоже нет.
  Алкоголь: 'Еда',
  Подписки: 'Связь и подписки',
  Образование: 'Прочее',
}

/** Дополнительные — всё, у чего есть родитель. */
export const EXTRA_CATEGORIES: readonly Category[] = CATEGORIES.filter(
  (c) => PARENT[c] !== undefined,
)

/**
 * Имена, под которыми категории жили раньше. Нужны, чтобы правка, сделанная
 * до переразбивки, нашла свою категорию, а не превратилась в «Прочее».
 */
const RENAMED: Readonly<Record<string, Category>> = {
  'Связь и интернет': 'Связь и подписки',
}

/** Привести имя категории к нынешнему. Неизвестное — «Прочее». */
export function currentName(name: string): Category {
  if (isCategory(name)) return name
  return RENAMED[name] ?? OTHER
}

/**
 * Что предлагать в выборе категории: девять основных, включённые
 * дополнительные и «не траты». Выключенные не предлагаются — их и включают
 * не отсюда, а разделом «Ещё категории», где рядом стоит цена вопроса.
 */
/**
 * Первые в списке выбора — то, на что владелец тратит и что называет чаще
 * всего: аренда, еда, развлечения, подарки, накопления.
 *
 * Отдельный список, а не порядок разрядов, по одной причине: «Накопления» —
 * не трата, у них план `move`, и в разряде основных им не место. А в выборе
 * место как раз есть: перевод себе на копилку человек называет ровно так же
 * часто, как перевод за аренду.
 */
export const FIRST_PICK: readonly Category[] = [
  'Аренда',
  'Еда',
  'Развлечения',
  'Подарки',
  'Накопления',
]

export function pickable(enabled: ReadonlySet<string>): Category[] {
  const all = [
    ...MAIN_CATEGORIES,
    ...EXTRA_CATEGORIES.filter((c) => enabled.has(c)),
    ...MOVE_CATEGORIES,
  ]
  const first = FIRST_PICK.filter((c) => all.includes(c))
  return [...first, ...all.filter((c) => !first.includes(c))]
}

/**
 * Свернуть категорию до включённой: выключенная уходит к родителю, родитель —
 * к своему родителю, и так до основной. Цепочка короткая, но цикл здесь честнее
 * одного шага: он не сломается, если родителей станет два уровня.
 */
export function collapse(category: Category, enabled: ReadonlySet<string>): Category {
  let current = category
  for (let step = 0; step < 4; step += 1) {
    const parent = PARENT[current]
    if (parent === undefined || enabled.has(current)) return current
    current = parent
  }
  return current
}

