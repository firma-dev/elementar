/** Куда попадает приход. Отдельная категория, а не расходная с плюсом. */
export const INCOME: Category = 'Доход'

/**
 * Перевод человеку, пока не сказано, за что он был.
 *
 * Это не «за что», а «кому»: за аренду, за пиво и жене на продукты банк
 * называет одним словом «перевод», и различить их по описанию нельзя — там
 * только номер телефона и имя. Категория здесь временная стоянка: разбор
 * переводов раскладывает её по настоящим категориям, по одному человеку за раз.
 */
export const PEOPLE: Category = 'Переводы людям'

export function isCategory(value: string): value is Category {
  return (CATEGORIES as readonly string[]).includes(value)
}

/** Одна операция выписки. */
export interface Tx {
  /**
   * Устойчивый идентификатор: считается из даты, суммы и описания, а не из
   * номера строки. Человек грузит выписку заново — ручные правки категорий
   * должны пережить перезагрузку, поэтому ключ не может зависеть от порядка.
   */
  id: string
  /** Дата операции, ISO `ГГГГ-ММ-ДД`. */
  date: string
  /**
   * Время операции, `ЧЧ:ММ`. `null` — банк его не дал.
   *
   * В картине года времени не нужно, и до переводов его выбрасывали при
   * разборе. Но перевод человеку описанием не объясняется — в нём только имя,
   * — и вспоминает его человек не по сумме, а по обстоятельствам: пятница,
   * половина одиннадцатого вечера — это было пиво, а не аренда.
   */
  time: string | null
  /** Копейки. Расход отрицательный, приход положительный. */
  amount: Kopeck
  /** Описание из выписки как есть, включая «OOO ROGA I KOPYTA». */
  description: string
  /** Код категории мерчанта, если банк его дал. */
  mcc: string | null
  /** Категория, проставленная банком. Используется как подсказка, не как истина. */
  bankCategory: string | null
  /**
   * Валюта, если банк не дал рублёвой суммы. `null` — рубли или уже
   * пересчитано банком.
   *
   * Нужна, чтобы человек мог назвать курс и увидеть правду вместо
   * предупреждения: без неё сумма в евро молча лежала в картине как рубли.
   */
  currency?: string | null
  /**
   * Ключ счёта, с которого прошла операция.
   *
   * Поле не служебное: по нему работает переключатель счетов сверху, и по нему
   * же различаются одинаковые покупки с разных карт. Раньше эту роль играл
   * префикс идентификатора, считанный из выписки, — и он менялся при каждой
   * новой выгрузке того же счёта (Д-026).
   */
  account: string
}

/** Операция с уже назначенной категорией. */
export interface Categorized extends Tx {
  category: Category
  /**
   * Откуда взялась категория. Порядок перечисления — порядок применения:
   * рука на операции, рука на получателе, вид операции, словарь, MCC,
   * столбец банка, ничего.
   */
  source: 'manual' | 'merchant' | 'operation' | 'rule' | 'mcc' | 'bank' | 'fallback'
}

/** Месяц как `ГГГГ-ММ`: ключ группировки в картине года. */
export type MonthKey = string

export function monthOf(date: string): MonthKey {
  return date.slice(0, 7)
}

