import type { Kopeck } from './money.js'

/**
 * Категории.
 *
 * Их два разряда, и это главное в списке. **Основных девять** — они стоят в
 * картине всегда. **Дополнительные** человек включает сам, когда различие ему
 * нужно: пока не включил, их траты складываются в родительскую категорию.
 *
 * Двадцать семь категорий сразу — это не точность, а работа: выбирая из
 * двадцати семи, человек каждый раз перечитывает список, и половина различий
 * ему не нужна вовсе. Кому-то важно отделить такси от транспорта, кому-то
 * алкоголь от продуктов, но одному человеку — не всё сразу.
 *
 * Список остаётся полным: старые правки ссылаются на имена, и убрать имя
 * значило бы потерять правку. Выключенная категория не исчезает — она
 * сворачивается в родителя и разворачивается обратно одним нажатием.
 */
