/**
 * Чей это банк.
 *
 * Имени банка в выписке нет — ни колонки, ни строки. Но выгрузка у каждого
 * банка своя: набор колонок, обороты в описаниях, формат номера карты. По ним
 * банк узнаётся так же, как человек узнаёт письмо по бланку.
 *
 * Ответ здесь всегда догадка, и наружу он выходит именно догадкой: приложение
 * предлагает имя, ставит его человек. Подписать чужие деньги наугад хуже, чем
 * не подписать вовсе — «Райффайзен» на счёте Т-Банка это не мелкая
 * неточность, а неверный ответ на вопрос «чьи это деньги».
 *
 * Таблица неполная и будет расти. Банк, которого здесь нет, не ломает ничего:
 * человек называет его руками один раз.
 */
import { normalize } from './text.js'

export interface BankGuess {
  /** Как называть банк человеку. */
  name: string
  /** Что именно совпало — показывается в подсказке, чтобы догадка не была слепой. */
  why: string
}

interface Signature {
  name: string
  /** Колонки, которые есть только у этого банка. Совпасть должны все. */
  columns: readonly string[]
  /** Обороты в описаниях. Достаточно одного. */
  marks?: readonly string[]
}

const SIGNATURES: readonly Signature[] = [
  {
    // «Округление на инвесткопилку» не встречается больше нигде: копилка,
    // округляющая покупки, — приём одного банка.
    name: 'Т-Банк',
    columns: ['ОКРУГЛЕНИЕ НА ИНВЕСТКОПИЛКУ'],
  },
  {
    name: 'Т-Банк',
    columns: ['БОНУСЫ РУБ', 'КЭШБЭК'],
  },
  {
    name: 'Альфа-Банк',
    columns: ['РЕФЕРЕНС ПРОВОДКИ'],
  },
  {
    name: 'Сбербанк',
    columns: ['СУММА В ВАЛЮТЕ СЧЕТА', 'КАТЕГОРИЯ'],
    marks: ['СБЕРБАНК ОНЛАЙН', 'SBERBANK ONLINE', 'SBOL'],
  },
  {
    // «Выполнено банком» рядом с «Детали операции (назначение платежа)» —
    // подпись выгрузки Райффайзена. Приход и расход там же двумя колонками.
    name: 'Райффайзен Банк',
    columns: ['ВЫПОЛНЕНО БАНКОМ', 'ДЕТАЛИ ОПЕРАЦИИ НАЗНАЧЕНИЕ ПЛАТЕЖА'],
  },
  {
    name: 'ВТБ',
    columns: ['НАЗВАНИЕ ОПЕРАЦИИ', 'ОСТАТОК ПО СЧЕТУ'],
    marks: ['ВТБ ОНЛАЙН', 'VTB'],
  },
]

/** Приведение имени колонки к сравнимому виду — то же, что в разборе выписки. */
function key(cell: string): string {
  return normalize(cell).trim()
}

/**
 * Догадка по шапке файла и по описаниям.
 *
 * Колонки должны совпасть все до одной: одна общая колонка вроде «Дата
 * операции» есть у всех, и по ней узнаётся не банк, а то, что это выписка.
 */
export function guessBank(
  header: readonly string[],
  descriptions: readonly string[],
): BankGuess | null {
  const columns = new Set(header.map(key))
  const text = descriptions.slice(0, 200).map(key).join(' ')

  for (const signature of SIGNATURES) {
    if (!signature.columns.every((column) => columns.has(column))) continue
    if (signature.marks !== undefined && !signature.marks.some((mark) => text.includes(mark))) {
      continue
    }
    const why =
      signature.columns.length === 1
        ? `в выгрузке есть колонка «${signature.columns[0]}»`
        : `в выгрузке есть колонки «${signature.columns.join('» и «')}»`
    return { name: signature.name, why }
  }
  return null
}
