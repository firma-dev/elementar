/**
 * План.
 *
 * Человек вводит три числа: сколько рассчитывает получить, сколько уходит на
 * обязательное и сколько откладывать. Четвёртое — «на жизнь» — не спрашивается,
 * потому что уже известно: это остаток от первых трёх (Д-026). Просить его
 * значило бы позволить сумме не сойтись.
 *
 * Пределы на день и на неделю тоже считаются, а не вводятся: месячный предел,
 * делённый на дни этого месяца. В феврале дневной предел выше, чем в январе, и
 * это правда, а не округление.
 */
import type { Kopeck } from './money.js'
import { daysInMonth, isDaily } from './period.js'
import type { PeriodKey } from './period.js'

export interface Plan {
  /** Сколько человек рассчитывает получить за месяц. */
  income: Kopeck
  /** Обязательные платежи: аренда, кредит, всё, что не обсуждается. */
  fixed: Kopeck
  /** Сколько откладывать за месяц. */
  save: Kopeck
  /**
   * Сколько всего лежит в копилке. Из выписки это не узнать — накопительный
   * счёт человек обычно не выгружает, — поэтому вводится рукой.
   */
  saved: Kopeck
  /**
   * Остаток на счёте, названный рукой. Ноль — не назван.
   *
   * Половина банков остаток в выгрузку не кладёт вовсе: в файле только
   * операции. Посчитать его из них нельзя — выписка начинается не с нуля, и
   * сумма операций это не остаток, а движение за период. Спросить у человека
   * дешевле, чем показывать пустое место там, где он каждый день смотрит.
   */
  onAccount: Kopeck
  /**
   * Дата, на которую назван остаток. После неё он пересчитывается операциями:
   * назвали в понедельник, во вторник потратили — приложение знает про вторник.
   */
  onAccountAt: string
  /**
   * Когда ждать ближайший приход, если человек поправил догадку.
   *
   * Приложение считает эту дату по ритму прошлых поступлений, но ритм знает не
   * всё: зарплату сдвинули на праздники, работу сменили, премию обещали к
   * пятнице. От этой даты считается главное число экрана — сколько можно
   * тратить в день, — и ошибаться в ней дороже, чем в любой другой.
   *
   * Пусто — держаться догадки. Дата в прошлом тоже считается пустой: она
   * осталась от прежнего месяца, и держаться за неё значит считать «сколько
   * тратить» на ноль дней.
   */
  arrivalAt: string
  /**
   * Цель: сколько всего надо накопить. Ноль — цели нет, и тогда не показывается
   * ни полоса, ни срок: пустая шкала врёт не меньше неверной.
   */
  goal: Kopeck
  /**
   * К какому месяцу, `ГГГГ-ММ`. Пустая строка — срок не назначен, и тогда
   * приложение говорит только «при нынешнем темпе — вот когда», не упрекая
   * человека сроком, которого он не ставил.
   */
  goalDate: string
}

export const EMPTY_PLAN: Plan = {
  income: 0,
  fixed: 0,
  save: 0,
  saved: 0,
  goal: 0,
  goalDate: '',
  onAccount: 0,
  onAccountAt: '',
  arrivalAt: '',
}

/**
 * Достроить план, прочитанный из хранилища.
 *
 * Планы, сохранённые до появления цели, полей `goal` и `goalDate` не имеют — в
 * них будет `undefined`, и любое сравнение с ним даст ложь молча. Разбираем
 * здесь один раз, а не проверяем в каждой формуле.
 */
export function normalizePlan(raw: Partial<Plan> | null | undefined): Plan {
  if (raw === null || raw === undefined) return EMPTY_PLAN
  const num = (v: unknown): Kopeck =>
    typeof v === 'number' && Number.isFinite(v) ? (Math.round(v) as Kopeck) : (0 as Kopeck)
  return {
    income: num(raw.income),
    fixed: num(raw.fixed),
    save: num(raw.save),
    saved: num(raw.saved),
    goal: num(raw.goal),
    goalDate: typeof raw.goalDate === 'string' ? raw.goalDate : '',
    onAccount: num(raw.onAccount),
    onAccountAt: typeof raw.onAccountAt === 'string' ? raw.onAccountAt : '',
    arrivalAt: typeof raw.arrivalAt === 'string' ? raw.arrivalAt : '',
  }
}

/** Заполнен ли план хоть на что-то. Пустой не показывается: пустая шкала врёт. */
export function hasPlan(plan: Plan): boolean {
  return plan.income > 0 || plan.fixed > 0 || plan.save > 0
}

/**
 * На жизнь — то, что остаётся после обязательного и откладываемого.
 *
 * Может выйти отрицательным: значит, план не сходится, и об этом надо сказать,
 * а не подтянуть до нуля. Подтянутый до нуля план выглядит выполнимым.
 */
export function living(plan: Plan): Kopeck {
  return (plan.income - plan.fixed - plan.save) as Kopeck
}

/**
 * Предел трат на период.
 *
 * Для длинных периодов предела нет: план месячный, а за прошедший год он
 * наверняка был другим. Умножить сегодняшний план на двенадцать и выдать это
 * за годовую норму — врать с точностью до копейки.
 */
export function limitFor(key: PeriodKey, edge: string, plan: Plan): Kopeck | null {
  if (!hasPlan(plan) || !isDaily(key)) return null
  const month = living(plan)
  if (month <= 0) return null
  switch (key) {
    case 'month':
      return month
    case 'week':
      return Math.round((month / daysInMonth(edge)) * 7) as Kopeck
    default:
      return Math.round(month / daysInMonth(edge)) as Kopeck
  }
}

/**
 * Сколько осталось отложить до месячной цели.
 *
 * Сравнивается именно отложенное за этот месяц, а не всё накопленное: цель
 * месячная, и копилка в сто тысяч не отменяет того, что в августе не отложено
 * ничего. Ноль — цель взята.
 */
export function toGoal(plan: Plan, setAside: Kopeck): Kopeck {
  return Math.max(0, plan.save - setAside) as Kopeck
}
