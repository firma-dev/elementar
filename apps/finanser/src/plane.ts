/**
 * Планы денег. Заменяют флаг «исключить переводы»: план — свойство категории,
 * а не настройка, которую человек забыл переключить.
 *
 * - `spend` — деньги ушли наружу, это трата;
 * - `move` — деньги переехали (перевод, наличные, погашение кредита), это не трата;
 * - `income` — деньги пришли.
 *
 * Разница видна на годовой сумме: снял в банкомате 50 000 и заплатил ими —
 * без планов это сто тысяч трат вместо пятидесяти.
 */
import type { Kopeck } from './money.js'
import type { Category } from './model.js'

export type Plane = 'spend' | 'move' | 'income'

/**
 * Категории, у которых план задан наперёд. Остальные решаются знаком суммы.
 * `move` сильнее знака: перевод со знаком минус — всё равно переезд, а не трата.
 */
const FIXED: Partial<Record<Category, Plane>> = {
  Переводы: 'move',
  Наличные: 'move',
  Кредиты: 'move',
  Доход: 'income',
}

/**
 * План одной операции. Знак решает всё, кроме `move`: возврат по «Продуктам» —
 * приход, а не отрицательная трата, иначе он вычтется из годовых продуктов и
 * картина года станет неправдой.
 */
export function planeOfTx(category: Category, amount: Kopeck): Plane {
  const fixed = FIXED[category]
  if (fixed === 'move') return 'move'
  return amount > 0 ? 'income' : 'spend'
}

/** Человеческое имя плана — для секции «Движения денег». */
export const PLANE_LABEL: Readonly<Record<Plane, string>> = {
  spend: 'траты',
  move: 'движения',
  income: 'поступления',
}
