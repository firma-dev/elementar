/**
 * Приведение описания к сравнимому виду. Отдельный модуль, потому что этим
 * пользуются и словарь категорий, и разбор получателей, и слой видов операции:
 * если бы он лежал в одном из них, остальные импортировали бы его по кругу.
 */
import { translit } from './translit.js'

/**
 * Верхний регистр, «ё» как «е», всё, что не буква и не цифра, — пробел. Строка
 * обрамляется пробелами, поэтому слово со значащим хвостовым пробелом
 * («МЕТРО ») не цепляет «МЕТРОПОЛИС».
 */
export function normalize(text: string): string {
  const body = text
    .toUpperCase()
    .replace(/Ё/g, 'Е')
    .replace(/[^0-9A-ZА-Я]+/gu, ' ')
    .trim()
  return ` ${body} `
}

/**
 * Сложенная форма: нормализация плюс транслитерация. Через неё проходят обе
 * стороны любого сравнения имён — и описание из выписки, и слово из словаря.
 * Благодаря этому «Пятёрочка» и «PYATEROCHKA» — одно и то же слово, и вести
 * словарь в двух написаниях больше не нужно.
 *
 * `normalize` остаётся отдельно: слой видов операции сравнивает русские обороты
 * («внутренний перевод», «снятие наличных»), и им транслитерация только мешает.
 */
export function fold(text: string): string {
  return translit(normalize(text))
}

/**
 * То же для слова словаря — но собственные пробелы слова сохраняются.
 *
 * Это не мелочь: «AZS » с хвостовым пробелом ловит заправку и не ловит
 * «AZSTROY», а «МЕТРО » — метро и не «Метрополис». `fold` такой пробел съедает,
 * потому что обрамляет строку сам; здесь он остаётся значащим.
 */
export function foldKeyword(keyword: string): string {
  return translit(
    keyword
      .toUpperCase()
      .replace(/Ё/g, 'Е')
      .replace(/[^0-9A-ZА-Я]+/gu, ' '),
  )
}
