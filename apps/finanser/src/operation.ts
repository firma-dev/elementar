/**
 * Служебные огрызки начала описания. Только предлоги: «и» сюда не входит
 * намеренно — в «Рога и Копыта» это часть имени, а союз из «оплата товаров и
 * услуг» вырезается вместе со всей фразой строкой выше.
 */
const LEFTOVER = new Set(['V', 'S', 'NA', 'PO', 'ZA', 'IZ', 'OT', 'DLYA'])

/**
 * Разбор описания на вид операции и остаток. Если ничего не опознано —
 * это обычная покупка, а остаток равен описанию целиком.
 */
export function operationOf(description: string): Operation {
  const norm = normalize(description)
  for (const rule of KINDS) {
    const mark = rule.marks.find((m) => norm.includes(` ${m} `) || norm.startsWith(` ${m}`))
    if (mark === undefined) continue
    let rest = norm
    for (const cut of rule.strip ?? [mark]) rest = rest.split(cut).join(' ')
    return { kind: rule.kind, rest: rest.trim(), category: rule.category }
  }
  return { kind: 'purchase', rest: norm.trim(), category: null }
}

/** Убирает служебные огрызки начала описания из уже нарезанных слов. */
export function dropLeftovers(words: readonly string[]): string[] {
  return words.filter((w) => !LEFTOVER.has(w))
}
