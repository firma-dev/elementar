/**
 * Вид операции по её описанию.
 *
 * Банк пишет в начале описания, что именно произошло: «Оплата в …»,
 * «Внутренний перевод …», «Снятие наличных …», «Пополнение …», «Кэшбэк …»,
 * «Плата за обслуживание», «Оплата услуг mBank.…». Это знание банка о своей же
 * операции — оно точнее любого словаря мерчантов, и его нельзя терять.
 *
 * Практическая причина завести слой: без него описание «Внешний перевод по
 * номеру телефона» попадало в «Связь и интернет» по слову «телефон». Сорок шесть
 * операций и четверть годовых трат оказывались не в той категории — и человек
 * этого не видел, потому что цифра выглядела правдоподобно.
 *
 * Поэтому вид операции определяется ДО словаря и, если он однозначен, словарь
 * уже не спрашивают.
 */
import type { Category } from './model.js'
import { normalize } from './text.js'

export type OperationKind =
  /** Перевод между своими счетами или другому человеку. */
  | 'transfer'
  /** Снятие или внесение наличных. */
  | 'cash'
  /** Пополнение счёта извне. */
  | 'topup'
  /** Кэшбэк, проценты на остаток, возврат банка. */
  | 'reward'
  /** Плата за обслуживание, комиссия, страховка кредита. */
  | 'fee'
  /** Перевод в копилку или на вклад — те же свои деньги. */
  | 'saving'
  /** Оплата услуг провайдера через банк: за словом идёт имя провайдера. */
  | 'utility'
  /** Обычная покупка у мерчанта. */
  | 'purchase'

export interface Operation {
  kind: OperationKind
  /**
   * Что осталось от описания после служебного начала — имя получателя.
   * Именно оно идёт в словарь правил и в ключ мерчанта.
   */
  rest: string
  /** Категория, если вид операции задаёт её однозначно. */
  category: Category | null
}

