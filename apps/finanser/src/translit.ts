/**
 * Кириллица к латинице. Нужна не для красоты: один и тот же магазин приезжает
 * в выписке то как «Пятёрочка», то как «PYATEROCHKA», и без приведения к одной
 * форме словарь приходится вести в двух написаниях — а значит, рано или поздно
 * в одном из них появится пропуск.
 *
 * Через эту таблицу проходят обе стороны сравнения: и описание из выписки, и
 * слово из словаря. Поэтому таблица не обязана быть филологически верной —
 * она обязана быть одинаковой.
 */

const MAP: Readonly<Record<string, string>> = {
  А: 'A',
  Б: 'B',
  В: 'V',
  Г: 'G',
  Д: 'D',
  Е: 'E',
  Ж: 'ZH',
  З: 'Z',
  И: 'I',
  Й: 'I',
  К: 'K',
  Л: 'L',
  М: 'M',
  Н: 'N',
  О: 'O',
  П: 'P',
  Р: 'R',
  С: 'S',
  Т: 'T',
  У: 'U',
  Ф: 'F',
  Х: 'KH',
  Ц: 'TS',
  Ч: 'CH',
  Ш: 'SH',
  Щ: 'SCH',
  Ъ: '',
  Ы: 'Y',
  Ь: '',
  Э: 'E',
  Ю: 'YU',
  Я: 'YA',
}

/** Строка уже в верхнем регистре и без «ё» — этим занимается `normalize`. */
export function translit(text: string): string {
  let out = ''
  for (const ch of text) out += MAP[ch] ?? ch
  return out
}
