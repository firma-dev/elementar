/**
 * Фирменный стиль Элементара: то, что принадлежит не корпусу, а самому проекту.
 *
 * Знак жил копией в каждом приложении, которому понадобился. Две копии одного
 * файла расходятся на первой же правке — поправят одну, и корпуса начнут
 * подписываться разными знаками. Относительный путь наружу («../../../») эту
 * беду убирает, но заводит другую: приложение начинает зависеть от того, где
 * лежит файл в чужом каталоге, и молча ломается при переносе.
 *
 * Отсюда пакет. Импорт `@elementar/brand/elementar.svg` не знает про раскладку
 * репозитория и переживает любой переезд.
 *
 * Канон §6 говорит «логотип — отдельный SVG, хранить рядом с этим файлом».
 * Копия в корне остаётся: она для человека, который открыл репозиторий и ищет
 * знак глазами. Для сборки — эта.
 */

/** Пропорции знака. Нужны, чтобы задать место под него до загрузки файла. */
export const LOGO_RATIO = { width: 563, height: 370 } as const

/** Отношение ширины к высоте: `inline-size: calc(высота * LOGO_ASPECT)`. */
export const LOGO_ASPECT = LOGO_RATIO.width / LOGO_RATIO.height
